#!/usr/bin/env python3
"""Fail when a unit's attack, death or move plays no sound, or a missing one.

Owner direction (2026-10-13): every sound effect is wired to its proper
clip, and the add-on carries its own clips (sounds/sw-*.wav) instead of a
private overlay that patched the installed copy.

For every [unit_type] in the generated unit files (gen_hte_units.py):
  - each attack has an [attack_anim] (by name, or a range-wide one) that
    plays a sound: a frame sound= or a SOUND:HIT_AND_MISS hit sound;
  - its death animation plays a sound;
  - every sound named exists: sounds/<name> in the add-on, or a mainline
    sound under the engine's data/core/sounds.

Usage: python3 production/tools/check_unit_sounds.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ADDON = ROOT / "addons/Star_Wars_Thrawn_Trilogy"
CORE_SOUNDS = Path.home() / "opt/wesnoth-1.19.27/data/core/sounds"
# Mainline sounds the generated units use (checked here when the engine data
# is not installed, as on CI).
MAINLINE = {"fist.ogg", "miss-1.ogg", "miss-2.ogg", "miss-3.ogg", "club.ogg", "club-miss.ogg", "spear.ogg",
            "spear-miss.ogg", "bow.ogg", "bow-miss.ogg", "bite.ogg", "tail.ogg", "sword-1.ogg",
            "dagger-swish.wav", "hiss.wav", "hiss-hit.wav"}


def sound_names(text: str) -> list[str]:
    names = re.findall(r"(?m)^\s*sound=(\S+)", text)
    for hit, miss in re.findall(r"\{SOUND:HIT_AND_MISS (\S+) (\S+) -?\d+\}", text):
        names += [hit, miss]
    return [n for name in names for n in name.split(",") if n and n != '""']


def exists(name: str) -> bool:
    if (ADDON / "sounds" / name).is_file():
        return True
    if CORE_SOUNDS.is_dir():
        return any(CORE_SOUNDS.rglob(name))
    return name in MAINLINE


def main() -> int:
    problems, units = [], 0
    for cfg in sorted((ADDON / "units").glob("*.cfg")):
        text = cfg.read_text(encoding="utf-8")
        if "GENERATED by production/tools/gen_hte_units.py" not in text:
            continue
        for block in re.finditer(r"(?ms)^\[unit_type\]\n(.*?)^\[/unit_type\]", text):
            body = block.group(1)
            # Only the base type: variations repeat it.
            top = re.sub(r"(?ms)^    \[variation\].*?^    \[/variation\]", "", body)
            uid = re.search(r"(?m)^    id=(\S+)$", top).group(1)
            units += 1
            anims = {}
            for a in re.finditer(r"(?ms)^    \[attack_anim\](.*?)^    \[/attack_anim\]", top):
                ab = a.group(1)
                key = re.search(r"\[filter_attack\]\s*(name|range)=(\S+)", ab)
                anims.setdefault(key.groups() if key else ("any", "*"), []).append(ab)
            for a in re.finditer(r"(?ms)^    \[attack\](.*?)^    \[/attack\]", top):
                ab = a.group(1)
                name = re.search(r"(?m)^        name=(\S+)", ab).group(1)
                rng = re.search(r"(?m)^        range=(\S+)", ab).group(1)
                found = anims.get(("name", name)) or anims.get(("range", rng)) or anims.get(("any", "*"))
                if not found:
                    problems.append(f"{uid}: attack {name} has no attack animation, so it is silent")
                elif not any(sound_names(f) for f in found):
                    problems.append(f"{uid}: attack {name} plays no sound")
            death = re.search(r"(?ms)^    \[death\](.*?)^    \[/death\]", top)
            if death and not sound_names(death.group(1)):
                problems.append(f"{uid}: death plays no sound")
            for name in sorted(set(sound_names(top))):
                if not exists(name):
                    problems.append(f"{uid}: sound {name} does not exist")
    for line in problems:
        print(line, file=sys.stderr)
    print(f"unit sounds: {units} unit types, {'FAIL' if problems else 'every attack and death has a sound'}")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
