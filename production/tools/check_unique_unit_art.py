#!/usr/bin/env python3
"""Fail when two unit types share the same sprite or portrait.

Owner rule (2026-10-12): every unit type must be told apart on the map, so a
new unit needs its own art made by the house rules
(gen_codex_unit_variants.py), never a copy of another unit's files. Three
units shipped as byte-identical copies (Smuggler Slicer, Myneyrshi Field
Medic) or as an earlier unit's superseded art (Wookiee Suppressor) before this
check existed.

Every [unit_type] in the generated unit files (the playable roster of
production/tools/gen_hte_units.py) is read for its image= (the
standing sprite) and profile= (the portrait). Two types fail if those files
have the same bytes. ALLOWED lists the pairs that share art on purpose.
Hand-written legacy files (units/infantry.cfg, spacecraft.cfg, vehicles.cfg)
are not checked: no scenario uses their unit types.

Usage: python3 production/tools/check_unique_unit_art.py
"""
from __future__ import annotations

import hashlib
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ADDON = ROOT / "addons/Star_Wars_Thrawn_Trilogy"

# Unit types that share art on purpose, as sorted pairs.
ALLOWED = {
    # The X-wing form of a hero speaks with the hero's own face.
    ("portrait", ("sw_hero_luke", "sw_hero_xwing_luke")),
    # The clone shares the owner-supplied sheet of the original (owner art,
    # 2026-10-06); to be decided by the owner.
    ("image", ("sw_hero_luke", "sw_hero_luuke")),
}


def unit_types() -> dict[str, dict[str, str]]:
    out = {}
    for cfg in sorted((ADDON / "units").glob("*.cfg")):
        text = cfg.read_text(encoding="utf-8")
        if "GENERATED by production/tools/gen_hte_units.py" not in text:
            continue
        for block in re.finditer(r"(?s)^\[unit_type\]\n(.*?)^\[/unit_type\]", text, re.M):
            body = block.group(1)
            uid = re.search(r"(?m)^    id=(\S+)$", body)
            if not uid:
                continue
            fields = {}
            for key in ("image", "profile"):
                m = re.search(rf"(?m)^    {key}=(\S+)$", body)
                if m:
                    fields[key] = m.group(1)
            out[uid.group(1)] = fields
    return out


def main() -> int:
    groups: dict[tuple[str, str], list[str]] = defaultdict(list)
    missing = []
    for uid, fields in unit_types().items():
        for key, rel in fields.items():
            path = ADDON / "images" / rel
            if not path.is_file():
                missing.append(f"{uid}: {key} {rel} is missing")
                continue
            groups[(key, hashlib.sha256(path.read_bytes()).hexdigest())].append(uid)
    problems = list(missing)
    for (key, _digest), ids in sorted(groups.items()):
        ids = sorted(set(ids))
        if len(ids) < 2:
            continue
        pairs = {(key, (a, b)) for i, a in enumerate(ids) for b in ids[i + 1:]}
        if not pairs <= ALLOWED:
            problems.append(f"{key} shared by {', '.join(ids)}: give each unit its own art "
                            "(production/tools/gen_codex_unit_variants.py)")
    for line in problems:
        print(line, file=sys.stderr)
    print(f"unit art: {len(unit_types())} unit types, {'FAIL' if problems else 'unique'}")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
