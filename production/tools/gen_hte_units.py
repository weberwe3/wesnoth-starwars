def attack_wml(a: dict, unit_slug: str, unit_id: str = "") -> str:
    lines = [
        "[attack]",
        f"    name={a['name']}",
        f"    description= _ \"{a['desc']}\"",
        f"    icon=attacks/{UNIT_ICONS.get((unit_id, a['name']), ICONS.get(a['name'], 'blank-attack'))}.png",
        f"    type={a['type']}",
        f"    range={a['range']}",
        f"    damage={a['damage']}",
        f"    number={a['number']}",
    ]
    if a.get("max_range"):
        lines.append("    min_range=1")
        lines.append(f"    max_range={a['max_range']}")
    if a["specials"]:
        lines.append("    [specials]")
        for sp in a["specials"]:
            lines.append(indent(SPECIALS[sp], 8))
        lines.append("    [/specials]")
    lines.append("[/attack]")
    del unit_slug
    return "\n".join(lines)


def unit_wml(u: dict) -> str:
    s = slug(u["id"])
    lines = [
        "[unit_type]",
        f"    id={u['id']}",
        f"    name= _ \"{u['name']}\"",
        f"    race={u['race']}",
    ]
    if u["gender"]:
        lines.append(f"    gender={u['gender']}")
    lines += [
        f"    image=units/{s}/standing.png",
        f"    profile=portraits/{s}.png",
        f"    hitpoints={u['hp']}",
        f"    movement_type={u['mt']}",
        f"    movement={u['mp']}",
        f"    experience={u['xp']}",
        f"    level={u['level']}",
        f"    alignment={u['alignment']}",
        f"    advances_to={u['advances'] or 'null'}",
        f"    cost={u['cost']}",
        f"    usage={u['usage']}",
        f"    description= _ \"{u['desc']}\"",
    ]
    if u["advances"] is None:
        lines.append("    {AMLA_DEFAULT}")
    if u["zoc"] == "no":
        lines.append("    zoc=no")
    if u["hero"]:
        lines.append("    # Named character: scenarios place the single instance and keep")
        lines.append("    # it out of recruit lists.")
        lines.append("    do_not_list=yes")
    system_abilities = [x for x in (force_ability(u["id"]), overwatch_ability(u["attacks"])) if x]
    if u["abilities"] or system_abilities:
        lines.append("    [abilities]")
        for ab in u["abilities"]:
            lines.append(indent(ABILITY_BUILDERS[ab](), 8))
        for block in system_abilities:
            lines.append(indent(block, 8))
        lines.append("    [/abilities]")
    for a in u["attacks"]:
        lines.append(indent(attack_wml(a, s, u["id"]), 4))
    lines.append(indent(animations(u), 4))
    lines.append("[/unit_type]")
    return "\n".join(lines)


def movetypes_wml() -> str:
    out = [HEADER, "# Movement types and races shared by Campaign I units.",
           "# Defense values are the chance to be hit; resistance is percent damage taken.", ""]
    for rid, (name, plural, desc) in RACES.items():
        out += [
            "[race]",
            f"    id={rid}",
            f"    name= _ \"race^{name}\"",
            f"    plural_name= _ \"race^{plural}\"",
            f"    description= _ \"{desc}\"",
            "    num_traits=2",
            "    ignore_global_traits=no",
            "[/race]",
            "",
        ]
    for mid, spec in MOVETYPES.items():
        flies = spec.get("flies", False)
        out += [f"# {spec['doc']}", "[movetype]", f"    name={mid}"]
        if flies:
            out.append("    flies=yes")
        out.append("    [movement_costs]")
        out += [f"        {t}={spec['move'].get(t, UNREACHABLE)}" for t in TERRAINS]
        out.append("    [/movement_costs]")
        out.append("    [defense]")
        out += [f"        {t}={spec['defense'][t]}" for t in TERRAINS]
        out.append("    [/defense]")
        out.append("    [resistance]")
        out += [f"        {k}={v}" for k, v in spec["resist"].items()]
        out.append("    [/resistance]")
        out += ["[/movetype]", ""]
    return "\n".join(out)


def render() -> dict[str, str]:
    files: dict[str, str] = {"hte_00_movetypes.cfg": movetypes_wml()}
    for fname, doc in FILES.items():
        units = [u for u in ROSTER if u["file"] == fname]
        body = [HEADER, f"# {doc}", ""]
        body += [unit_wml(u) + "\n" for u in units]
        files[f"{fname}.cfg"] = "\n".join(body)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    ids = [u["id"] for u in ROSTER]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate unit id in roster")
    stale = []
    for name, text in render().items():
        path = UNITS_DIR / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated unit files: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{'checked' if args.check else 'wrote'} {len(ROSTER)} unit types")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
