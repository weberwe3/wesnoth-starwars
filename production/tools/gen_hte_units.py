def rank_data_lua() -> str:
    lines = [
        "-- Generated by production/tools/gen_hte_units.py: do not edit.",
        "-- Rank insignia style and starting rank per unit type (lua/sw_rank.lua).",
        "return {",
    ]
    for u in ROSTER:
        style = rank_style(u["id"])
        if style:
            lines.append(f'\t{u["id"]} = {{ style = "{style}", base = {RANK_BASE.get(u["id"], 0)} }},')
    lines.append("}")
    return "\n".join(lines) + "\n"


