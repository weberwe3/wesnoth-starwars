# --- weapon ranges and aimed shots (owner design, 2026-10-03) ---------------
# Ranged attacks reach targets up to max_range hexes away (native 1.19
# min_range/max_range). Accuracy falls 10% per hex beyond the first. The
# range is shown as a weapon special ("range N") so it appears with damage
# and strikes in the weapon information.
#   pistols 1, rifles and long arms 2, heavy and crew-served 3; Han Solo's
#   DL-44 heavy blaster pistol is the exception at 2. Bombs drop on the hex
#   beneath (1); guided torpedoes reach 3 without falloff.
#   Jedi blaster deflection reaches 2 (balance review 2026-10-04): it only
#   returns fire, and at 1 a rifleman 2 hexes away shot a Jedi without reply.
WEAPON_RANGES = {
    # infantry
    "blaster_pistol": 1, "hold_out_blaster": 1, "stun_blaster": 1, "sprayer": 1,
    "heavy_blaster_pistol": 2,   # Han Solo's DL-44 (only Han carries it)
    "blaster_rifle": 2, "blaster_carbine": 2, "bowcaster": 2, "bike_blaster": 2, "bow": 2,
    "concussion_grenade": 2, "force_lightning": 2, "deflection": 2,
    "eweb_repeater": 3, "twin_blaster_cannon": 3,
    # craft
    "laser_cannons": 2, "ion_cannon": 2, "point_defense": 1, "concussion_bombs": 1,
    "proton_torpedoes": 3, "turbolasers": 3, "ion_cannons": 3,
}
NO_FALLOFF = {"proton_torpedoes"}       # guided
RANGE_FALLOFF = 10                      # % to hit lost per hex beyond the first
# Aimed shot: one strike fewer, +20% to hit, needs 2+ hexes, attack only.
AIMED_WEAPONS = {"blaster_rifle", "blaster_carbine", "bowcaster", "bow", "heavy_blaster_pistol"}
AIMED_BONUS = 20


def range_special(name: str, max_range: int) -> str:
    if max_range <= 1:
        return (
            "[chance_to_hit]\n"
            "    id=sw_special_range\n"
            "    name= _ \"range 1\"\n"
            "    description= _ \"Close range: only adjacent targets.\"\n"
            "    add=0\n"
            "    cumulative=yes\n"
            "[/chance_to_hit]"
        )
    if name in NO_FALLOFF:
        return (
            "[chance_to_hit]\n"
            "    id=sw_special_range\n"
            f"    name= _ \"range {max_range}, guided\"\n"
            f"    description= _ \"Reaches targets up to {max_range} hexes away. Guided: no accuracy lost with distance.\"\n"
            "    add=0\n"
            "    cumulative=yes\n"
            "[/chance_to_hit]"
        )
    return (
        "[chance_to_hit]\n"
        "    id=sw_special_range\n"
        f"    name= _ \"range {max_range}\"\n"
        f"    description= _ \"Reaches targets up to {max_range} hexes away. Each hex beyond the first lowers the "
        f"chance to hit by {RANGE_FALLOFF}%.\"\n"
        # Special formulas see the combatants as attacker and defender.
        f"    sub=\"({RANGE_FALLOFF} * (distance_between(attacker.loc, defender.loc) - 1))\"\n"
        "    cumulative=yes\n"
        "[/chance_to_hit]"
    )


# Flanking (owner design, 2026-10-04): every weapon gets +FLANK_BONUS% chance to
# hit for each unit hostile to the target standing on the target's far side,
# up to FLANK_MAX%. Defined once as a WML macro in units/00_sw_specials.cfg
# (sorted first in the units directory, so it exists before any unit file
# uses it) and referenced from every attack.
FLANK_BONUS = 10
FLANK_MAX = 20

# Hostile, armed, not petrified units adjacent to the target and farther from
# the attacker than the target is: for a melee attack, the three hexes behind
# the target; for a shot from range, the hexes behind it along the line of
# fire. In a special's [filter_opponent] formula, self and loc are the target
# and other is the attacking unit (installed src/units/filter.cpp).
# Engine details (src/formula): inside filter()/map(), self, loc and other
# names resolve against each list element first, so the target, its hex and
# the attacker's hex are bound up front with sw_-named where variables; WFL
# "and" evaluates both sides, so empty hexes are dropped before unit fields
# are read. The count is followed by the tier test, then the where clause.
FLANKERS_WFL = (
    "size(filter(filter(map(filter(adjacent_locs(sw_here), 'sw_l', "
    "distance_between(sw_l, sw_from) > sw_dist), 'sw_l', unit_at(sw_l)), "
    "'sw_u', sw_u != null()), 'sw_u', enemy_of(sw_target, sw_u) and not sw_u.petrified and size(sw_u.attacks) > 0))"
)
FLANKERS_WHERE = ("where sw_target = self, sw_here = loc, sw_from = other.loc, "
                  "sw_dist = distance_between(loc, other.loc)")


def flanking_specials_wml() -> str:
    """units/00_sw_specials.cfg: the SW_SPECIAL_FLANKING macro."""
    tiers = []
    steps = FLANK_MAX // FLANK_BONUS
    for n in range(1, steps + 1):
        bonus = n * FLANK_BONUS
        test = f"= {n}" if n < steps else f">= {n}"
        tiers.append(
            "    [chance_to_hit]\n"
            "        id=sw_special_flanking\n"
            f"        name= _ \"flanking +{bonus}%\"\n"
            "        # Empty inactive name and description: shown only while it applies.\n"
            "        name_inactive=\"\"\n"
            f"        description= _ \"The target is flanked: allies stand on its far side. +{FLANK_BONUS}% chance to "
            f"hit for each, up to +{FLANK_MAX}%.\"\n"
            "        description_inactive=\"\"\n"
            f"        add={bonus}\n"
            "        cumulative=yes\n"
            "        active_on=offense\n"
            "        [filter_opponent]\n"
            f"            formula=\"({FLANKERS_WFL} {test}) {FLANKERS_WHERE}\"\n"
            "        [/filter_opponent]\n"
            "    [/chance_to_hit]\n"
        )
    return (
        HEADER
        + "\n"
        "# Weapon specials shared by every unit file. Named 00_* so the directory\n"
        "# include loads it first: a macro must be defined before it is used.\n"
        "\n"
        "# Flanking: when attacking, +10% chance to hit for each unit hostile to the\n"
        "# target that stands adjacent to it on its far side -- farther from the\n"
        "# attacker than the target is (for a melee attack, the three hexes behind\n"
        "# the target). At most +20%. Petrified and unarmed units do not count, and\n"
        "# it never applies to return fire. One special per tier, so the attack\n"
        "# dialog names the exact bonus, and neither is listed when inactive.\n"
        "#define SW_SPECIAL_FLANKING\n"
        + "".join(tiers)
        + "#enddef\n"
    )


def aimed_special() -> str:
    return (
        "[chance_to_hit]\n"
        "    id=sw_special_aimed\n"
        "    name= _ \"aimed shot\"\n"
        f"    description= _ \"Taking a moment to aim: one shot fewer, +{AIMED_BONUS}% chance to hit. Needs at least two "
        "hexes of distance (no time to aim at point-blank range) and can only be used when attacking.\"\n"
        f"    add={AIMED_BONUS}\n"
        "    cumulative=yes\n"
        "[/chance_to_hit]\n"
        "[disable]\n"
        "    id=sw_special_aimed_attack_only\n"
        "    active_on=defense\n"
        "[/disable]"
    )


def expanded_attacks(u: dict) -> list[dict]:
    """The unit's attacks with ranges applied and aimed-shot variants added
    right after the weapons that have one."""
    out = []
    for a in u["attacks"]:
        a = dict(a)
        if a["range"] == "ranged":
            a["max_range"] = WEAPON_RANGES.get(a["name"], a.get("max_range") or 1)
        out.append(a)
        if a["range"] == "ranged" and a["name"] in AIMED_WEAPONS and a["max_range"] >= 2 and a["number"] >= 2:
            aimed = dict(a)
            aimed.update(name=a["name"] + "_aimed", desc=a["desc"] + " (aimed)", number=a["number"] - 1,
                         base=a["name"], min_range=2, aimed=True)
            out.append(aimed)
    return out


def attack_wml(a: dict, unit_slug: str, unit_id: str = "") -> str:
    lines = [
        "[attack]",
        f"    name={a['name']}",
        f"    description= _ \"{a['desc']}\"",
        f"    icon=attacks/{UNIT_ICONS.get((unit_id, a.get('base', a['name'])), ICONS.get(a.get('base', a['name']), 'blank-attack'))}.png",
        f"    type={a['type']}",
        f"    range={a['range']}",
        f"    damage={a['damage']}",
        f"    number={a['number']}",
    ]
    if a.get("max_range"):
        lines.append(f"    min_range={a.get('min_range', 1)}")
        lines.append(f"    max_range={a['max_range']}")
    blocks = [SPECIALS[sp] for sp in a["specials"]]
    if a["range"] == "ranged" and a.get("max_range"):
        blocks.append(range_special(a.get("base", a["name"]), a["max_range"]))
    if a.get("aimed"):
        blocks.append(aimed_special())
    blocks.append("{SW_SPECIAL_FLANKING}")
    if blocks:
        lines.append("    [specials]")
        for block in blocks:
            lines.append(indent(block, 8))
        lines.append("    [/specials]")
    lines.append("[/attack]")
    del unit_slug
    return "\n".join(lines)


# Unarmed variations (owner direction 2026-10-06): a hero who loses his weapon
# in a mission shows his own unarmed sprite set until he recovers it. The
# variation is the full unit (inherit=no, so no positional merging of
# animations) with its art in units/<slug>-unarmed/ and an animation for the
# fists the mission's object gives him. Scenarios switch it with the
# SW_UNARMED / SW_ARMED macros (utils/hte_macros.cfg).
UNARMED_VARIATIONS = {"sw_hero_luke": "fists"}


def unarmed_variation(u: dict) -> str:
    s = slug(u["id"])
    art = f"{s}-unarmed"
    body = unit_wml(u, with_variations=False).replace(f"units/{s}/", f"units/{art}/").split("\n")
    body = [line for line in body[1:-1] if not line.startswith("    id=")]
    melee = melee_anim(f"units/{art}", u["id"], {"name": UNARMED_VARIATIONS[u["id"]]})
    return "\n".join(["[variation]", "    variation_id=unarmed", "    variation_name= _ \"unarmed\"",
                      "    hide_help=yes", "    inherit=no"] + body + [indent(melee, 4), "[/variation]"])


def unit_wml(u: dict, with_variations: bool = True) -> str:
    s = slug(u["id"])
    lines = [
        "[unit_type]",
        f"    id={u['id']}",
        f"    name= _ \"{u['name']}\"",
        f"    race={u['race']}",
    ]
    if u["gender"]:
        lines.append(f"    gender={u['gender']}")
    lines += [
        f"    image=units/{s}/standing.png",
        f"    profile=portraits/{s}.png",
        f"    hitpoints={u['hp']}",
        f"    movement_type={u['mt']}",
        f"    movement={u['mp']}",
        f"    experience={u['xp']}",
        f"    level={u['level']}",
        f"    alignment={u['alignment']}",
        f"    advances_to={u['advances'] or 'null'}",
        f"    cost={u['cost']}",
        f"    usage={u['usage']}",
        f"    description= _ \"{u['desc']}\"",
    ]
    if u["advances"] is None:
        lines.append("    {AMLA_DEFAULT}")
    if u["zoc"] == "no":
        lines.append("    zoc=no")
    if u["hero"]:
        lines.append("    # Named character: scenarios place the single instance and keep")
        lines.append("    # it out of recruit lists.")
        lines.append("    do_not_list=yes")
    system_abilities = [x for x in (force_ability(u["id"]), overwatch_ability(u["attacks"]), ew_ability(u["id"]),
                                    observer_ability(u["id"]), anti_air_ability(u["id"])) if x]
    if u["abilities"] or system_abilities:
        lines.append("    [abilities]")
        for ab in u["abilities"]:
            lines.append(indent(ABILITY_BUILDERS[ab](), 8))
        for block in system_abilities:
            lines.append(indent(block, 8))
        lines.append("    [/abilities]")
    for a in expanded_attacks(u):
        lines.append(indent(attack_wml(a, s, u["id"]), 4))
    lines.append(indent(animations(u), 4))
    if u["id"] in FLYOVER_CRAFT and with_variations:
        lines.append(indent(flyover_variation(), 4))
    if u["id"] in UNARMED_VARIATIONS and with_variations:
        lines.append(indent(unarmed_variation(u), 4))
    lines.append("[/unit_type]")
    return "\n".join(lines)


def movetypes_wml() -> str:
    out = [HEADER, "# Movement types and races shared by Campaign I units.",
           "# Defense values are the chance to be hit; resistance is percent damage taken.", ""]
    for rid, (name, plural, desc) in RACES.items():
        out += [
            "[race]",
            f"    id={rid}",
            f"    name= _ \"race^{name}\"",
            f"    plural_name= _ \"race^{plural}\"",
            f"    description= _ \"{desc}\"",
            "    num_traits=2",
            "    ignore_global_traits=no",
            "[/race]",
            "",
        ]
    for mid, spec in MOVETYPES.items():
        flies = spec.get("flies", False)
        out += [f"# {spec['doc']}", "[movetype]", f"    name={mid}"]
        if flies:
            out.append("    flies=yes")
        out.append("    [movement_costs]")
        out += [f"        {t}={spec['move'].get(t, UNREACHABLE)}" for t in TERRAINS]
        out.append("    [/movement_costs]")
        out.append("    [defense]")
        out += [f"        {t}={spec['defense'][t]}" for t in TERRAINS]
        out.append("    [/defense]")
        out.append("    [resistance]")
        out += [f"        {k}={v}" for k, v in spec["resist"].items()]
        out.append("    [/resistance]")
        out += ["[/movetype]", ""]
    return "\n".join(out)


def render() -> dict[str, str]:
    files: dict[str, str] = {"00_sw_specials.cfg": flanking_specials_wml(), "hte_00_movetypes.cfg": movetypes_wml()}
    for fname, doc in FILES.items():
        units = [u for u in ROSTER if u["file"] == fname]
        body = [HEADER, f"# {doc}", ""]
        body += [unit_wml(u) + "\n" for u in units]
        files[f"{fname}.cfg"] = "\n".join(body)
    files["../lua/sw_rank_data.lua"] = rank_data_lua()
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    ids = [u["id"] for u in ROSTER]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate unit id in roster")
    stale = []
    for name, text in render().items():
        path = UNITS_DIR / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated unit files: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{'checked' if args.check else 'wrote'} {len(ROSTER)} unit types")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
