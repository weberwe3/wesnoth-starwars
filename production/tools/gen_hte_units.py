def slug(unit_id: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", unit_id.casefold()).strip("-")


def frame(image: str, duration: int) -> str:
    return f"[frame]\n    image={image}\n    duration={duration}\n[/frame]"


def animations(u: dict) -> str:
    s = slug(u["id"])
    base = f"units/{s}"
    has_melee = any(a["range"] == "melee" for a in u["attacks"])
    has_ranged = any(a["range"] == "ranged" for a in u["attacks"])
    blocks = [
        "[standing_anim]\n" + indent(frame(f"{base}/standing.png", 1000), 4) + "\n[/standing_anim]",
        "[idle_anim]\n" + indent(frame(f"{base}/idle-1.png", 300), 4) + "\n"
        + indent(frame(f"{base}/idle-2.png", 300), 4) + "\n[/idle_anim]",
        "[movement_anim]\n" + indent(with_sound(frame(f"{base}/move-1.png", 150),
                                                None if u["id"] in STATIONARY else MOVE_SOUNDS.get(u["mt"])), 4) + "\n"
        + indent(frame(f"{base}/move-2.png", 150), 4) + "\n[/movement_anim]",
    ]
    # The melee and ranged frames are always wired so the art contract stays
    # complete; the range filter keeps an absent attack range from using them.
    melee = [a for a in u["attacks"] if a["range"] == "melee"]
    for a in melee or [None]:
        blocks.append(melee_anim(base, u["id"], a))
    ranged = [a for a in u["attacks"] if a["range"] == "ranged"]
    # One animation per ranged attack, each firing its own projectile. A unit
    # without a ranged attack keeps one plain ranged block so its art set is
    # still fully referenced.
    for a in ranged or [None]:
        blocks.append(ranged_anim(base, u["id"], a))
    del has_melee, has_ranged
    blocks.append("[defend]\n" + indent(frame(f"{base}/defend.png", 250), 4) + "\n[/defend]")
    blocks.append(
        "[death]\n" + indent(with_sound(frame(f"{base}/death-1.png", 200),
                                        DEATH_OVERRIDES.get(u["id"], DEATH_SOUNDS.get(u["mt"]))), 4) + "\n"
        + indent(frame(f"{base}/death-2.png", 400), 4) + "\n[/death]"
    )
    return "\n".join(blocks)


