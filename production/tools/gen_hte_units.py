                "[dummy]\n"
                "    id=sw_ability_overwatch\n"
                f"    weapons={weapon}\n"
                f"    range={rng}\n"
                f"    reactions={reactions}\n"
                f"    accuracy={accuracy}\n"
                "    damage=100\n"
                "    name= _ \"overwatch\"\n"
